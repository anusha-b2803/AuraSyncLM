"""
Demo Execution: End-to-End MMLF RAG Pipeline with 6-Stage Trace Logging
======================================================================
Traces and logs:
1. Original-query retrieval from ChromaDB.
2. Adaptive decision and generated sub-queries.
3. Pseudo-passage generation using configured Ollama model.
4. Independent retrieval for the original query and each generated passage.
5. RRF fusion and final retrieved contexts.
6. Final answer grounded in those contexts.
"""

import os
import sys
import logging
import json

if sys.platform == 'win32':
    try:
        sys.stdout.reconfigure(encoding='utf-8')
        sys.stderr.reconfigure(encoding='utf-8')
    except Exception:
        pass

os.environ["ANONYMIZED_TELEMETRY"] = "False"
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"

# Configure root logger with visible timestamps and INFO level
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[logging.StreamHandler(sys.stdout)]
)

logger = logging.getLogger("AuraSyncLM")

from chatbot import retrieve, mmlf_retrieve, generate_answer, get_ollama_status

def main():
    query = "How does MMLF use Reciprocal Rank Fusion to combine multiple queries and passages without score normalization?"
    user_id = "default"

    print("\n" + "=" * 80)
    print("[*] AURASYNC LM: END-TO-END 6-STAGE PIPELINE EXECUTION")
    print(f"Query: \"{query}\"")
    print("=" * 80 + "\n")

    # Verify Ollama status
    status = get_ollama_status()
    logger.info(f"Ollama Service Status: {status.get('message', 'Active')}")

    # Stage 1 to 5: Run MMLF Pipeline
    logger.info("Initiating MMLF Neural Pipeline...")
    mmlf_result = mmlf_retrieve(query, user_id=user_id, top_k=4)

    contexts = mmlf_result.get("contexts", [])

    # Stage 6: Grounded Answer Generation
    logger.info(f"Passing {len(contexts)} fused context(s) to LLM for final grounded synthesis...")
    final_answer = generate_answer(query, json.dumps(contexts))

    print("\n" + "=" * 80)
    print("[+] FINAL GROUNDED ANSWER GENERATED BY OLLAMA:")
    print("=" * 80)
    print(final_answer)
    print("=" * 80 + "\n")

if __name__ == "__main__":
    main()
